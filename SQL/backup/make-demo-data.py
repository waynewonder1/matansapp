"""Builds demo-data.js (used only by demo mode, index.html?demo) from files already in the repo.

Usage (from the project folder):
  python -I SQL/backup/make-demo-data.py

It copies the reference data the demo needs: classes, learning areas, terms, the question bank
(competencies and question_variants) from SQL/0-rebuild-from-empty.sql, and the curriculum list from
migration 8. None of it is about a child or a staff member: staff ids (created_by, approved_by, teacher_id)
are removed. The made-up children are created in demo.js, not here.
Run it again after regenerating the rebuild file, so the demo's question bank stays current.
"""
import json, os, re, uuid

here = os.path.dirname(os.path.abspath(__file__))
root = os.path.dirname(os.path.dirname(here))
rebuild = open(os.path.join(root, "SQL", "0-rebuild-from-empty.sql"), encoding="utf-8").read()
m8 = open(os.path.join(root, "SQL", "Migration 8 checks curriculum reports"), encoding="utf-8").read()

KEEP = ["classes", "learning_areas", "terms", "competencies", "question_variants"]
STAFF_COLS = {"created_by", "approved_by", "teacher_id"}
data = {k: [] for k in KEEP}
for t, js in re.findall(r"^insert into public\.(\w+) select \* from jsonb_populate_record\(null::public\.\w+, '(.*)'\) on conflict do nothing;$", rebuild, re.M):
    if t in data:
        row = json.loads(js.replace("''", "'"))
        for c in STAFF_COLS:
            if c in row:
                row[c] = None
        data[t].append(row)

# Curriculum list from migration 8: (cls, area, code, strand, name, lessons, term, sort)
q = r"'((?:[^']|'')*)'"
pat = re.compile(r"\('(PG|PP1|PP2)',(\d),%s,(?:%s|null),%s,\s*(\d+|null),\s*(\d+|null),\s*(\d+)\)" % (q, q, q))
ci = []
for cls, area, code, strand, name, lessons, term, sort in pat.findall(m8[m8.index("insert into curriculum_items"):]):
    un = lambda s: s.replace("''", "'")
    ci.append({"id": str(uuid.uuid5(uuid.NAMESPACE_URL, f"matan-demo/{cls}/{area}/{code}")), "cls": cls, "area": int(area), "code": un(code),
               "strand": un(strand) or None, "name": un(name), "lessons": None if lessons == "null" else int(lessons),
               "term": None if term == "null" else int(term), "sort": int(sort)})
data["curriculum_items"] = ci

out = os.path.join(root, "demo-data.js")
with open(out, "w", encoding="utf-8", newline="\n") as f:
    f.write("/* Reference data for demo mode only (index.html?demo). Generated by SQL/backup/make-demo-data.py. Do not edit by hand.\n")
    f.write("   Question bank, curriculum, classes and terms: no learner, guardian or staff details. */\n")
    f.write("window.MATAN_DEMO_DATA=" + json.dumps(data, ensure_ascii=False, separators=(",", ":")) + ";\n")
print("Wrote", out, {k: len(v) for k, v in data.items()})
