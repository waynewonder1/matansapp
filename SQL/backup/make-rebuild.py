"""Builds SQL/0-rebuild-from-empty.sql from the five CSV files the export queries produce.

Usage (from the project folder):
  python -I SQL/backup/make-rebuild.py tables.csv keys.csv code.csv security.csv data.csv

tables.csv   = result of export-1a-tables.sql
keys.csv     = result of export-1b-keys.sql
code.csv     = result of export-1c-code.sql
security.csv = result of export-1d-security.sql
data.csv     = result of export-2-starting-data.sql

The CSVs themselves are not kept in the repo. The output has no learner, guardian or staff details.
"""
import csv, os, re, sys
from datetime import date

if len(sys.argv) != 6:
    sys.exit(__doc__)
tables, keys, code, security, data = (list(csv.DictReader(open(p, encoding="utf-8"))) for p in sys.argv[1:])
here = os.path.dirname(os.path.abspath(__file__))
root = os.path.dirname(os.path.dirname(here))

def by_part(rows, *parts, field="part"):
    return [r["statement"].strip() for r in rows if r[field] in parts]

# Sequences used by "default nextval(...)": create them first, then tie each one to its column.
seqs = []  # (table, column, sequence) for plain "id ... default nextval(...)" columns
allseq = []  # every sequence any default uses, for example record_seq inside assessment_records.public_id
for r in tables:
    for col, seq in re.findall(r"^\s+(\w+) \w[^\n]*default nextval\('([\w.]+)'::regclass\)", r["statement"], re.M):
        seqs.append((r["table_name"], col, seq.split(".")[-1]))
    for seq in re.findall(r"nextval\('([\w.]+)'::regclass\)", r["statement"]):
        if seq.split(".")[-1] not in allseq:
            allseq.append(seq.split(".")[-1])

# Starting data: a class's teacher is a staff account, which will not exist in a new database.
start = []
for r in sorted(data, key=lambda r: r["section"]):
    if r["section"] == "6":
        continue  # replaced by the setval lines below, which cover every sequence
    s = r["statement"].strip()
    if s.startswith("insert into public.classes "):
        s = re.sub(r'"teacher_id": "[0-9a-f-]{36}"', '"teacher_id": null', s)
    start.append(s)

# The curriculum list (261 sub-strands) comes from migration 8, which is already in the repo.
m8 = open(os.path.join(root, "SQL", "Migration 8 checks curriculum reports"), encoding="utf-8").read()
cur = m8[m8.index("insert into curriculum_items"):].strip().rstrip(";") + "\non conflict do nothing;"

out = [
    "-- 0-rebuild-from-empty.sql: rebuilds the whole Matan database in a NEW, EMPTY Supabase project.",
    "-- Generated by SQL/backup/make-rebuild.py from the export queries in SQL/backup. Do not edit by hand; re-export instead.",
    f"-- Exported from the live database on {date.today().isoformat()}. It includes every migration run before that date;",
    "-- afterwards, run only migrations added to the repo after that date.",
    "-- It holds no learner, guardian or staff details: only the structure, the security rules, classes, areas, terms,",
    "-- the question bank and the curriculum list. Learner records come back only from a data backup.",
    "-- After running it: create the director's login (Authentication > Users), then add that user to the staff table.",
    "",
    "set check_function_bodies = off;  -- lets functions be created before the ones they call",
    "",
    "-- 1. sequences",
    *[f"create sequence if not exists public.{s};" for s in allseq],
    "",
    "-- 2. types",
    *by_part(keys, "1"),
    "",
    "-- 3. tables",
    *[r["statement"].strip() for r in tables],
    *[f"alter sequence public.{s} owned by public.{t}.{c};" for t, c, s in seqs],
    "",
    "-- 4. keys and checks",
    *by_part(keys, "2"),
    "",
    "-- 5. links between tables",
    *by_part(keys, "3"),
    "",
    "-- 6. indexes",
    *by_part(keys, "4"),
    "",
    "-- 7. views and functions",
    *by_part(code, "1"),
    "",
    "-- 8. triggers",
    *by_part(code, "2"),
    "",
    "-- 9. row level security and its rules",
    *by_part(security, "1"),
    *by_part(security, "2"),
    "",
    "-- 10. starting data",
    *start,
    "",
    "-- 11. the curriculum (from migration 8)",
    cur,
    "",
    "-- 12. new ids carry on after the copied ones",
    *[f"select setval('public.{s}', greatest(1, (select coalesce(max({c}), 1) from public.{t})));" for t, c, s in seqs],
    "",
    "notify pgrst, 'reload schema';",
    "",
]
dest = os.path.join(root, "SQL", "0-rebuild-from-empty.sql")
open(dest, "w", encoding="utf-8", newline="\n").write("\n".join(out))
print("Wrote", dest, "with", len(tables), "tables,", len(by_part(security, "2")), "policies,", len(start), "starting rows")
